#!/bin/bash
# Тестирование Этапа 2: Параметры командной строки
# Проверка отладочного вывода всех параметров при запуске

set -e

SCRIPT_DIR="$(dirname "$0")"
cd "$SCRIPT_DIR/.."

echo "=========================================================="
echo "  [Тест 1] Запуск без параметров"
echo "=========================================================="
echo "exit" | python3 main.py --cli

echo ""
echo "=========================================================="
echo "  [Тест 2] Запуск только с параметром --vfs"
echo "=========================================================="
echo "exit" | python3 main.py --cli --vfs vfs_samples/minimal.json

echo ""
echo "=========================================================="
echo "  [Тест 3] Запуск только с параметром --script"
echo "=========================================================="
python3 main.py --cli --script scripts/test_config.sh

echo ""
echo "=========================================================="
echo "  [Тест 4] Запуск с обоими параметрами (--vfs и --script)"
echo "=========================================================="
python3 main.py --cli --vfs vfs_samples/full.json --script scripts/test_config.sh

echo ""
echo ">>> Все тесты параметров командной строки успешно завершены!"

# Стартовый скрипт для Этапа 3 (VFS)
# Тестирование базовых команд с VFS

# Тест ls в корне
ls

# Тест cd в поддиректорию
cd home
ls

# Тест cd с вложенностью
cd user
ls

# Тест cd ..
cd ..
ls

# Тест cd в абсолютный путь
cd /etc
ls

# Тест cd в корень
cd /
ls

# Тест парсера с кавычками
ls "home"

# Тест ошибки: несуществующий путь
ls nonexistent

# Тест date
date

# Тест exit
exit

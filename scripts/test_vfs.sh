# Стартовый скрипт для тестирования VFS (не менее 3 уровней вложенности)
# Файловая система: vfs_samples/full.json

# Просмотр корневого каталога
ls

# Переход на 1-й уровень: home
cd home
ls

# Переход на 2-й уровень: user
cd user
ls

# Переход на 3-й уровень: documents
cd documents
ls

# Просмотр файла
ls report.txt

# Переход по относительному пути на два уровня вверх
cd ../..
ls

# Переход по абсолютному пути в глубокую директорию
cd /home/user/documents
ls

# Проверка парсера с аргументами в кавычках
ls "report.txt"

# Сохранение состояния VFS в файл
vfs-save saved_full.json

# Обработка ошибок: переход в несуществующий каталог
cd /nonexistent/path

# Обработка ошибок: попытка cd в файл
cd /etc/hosts

# Возврат в корень
cd /
ls

exit

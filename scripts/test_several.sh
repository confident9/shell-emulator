# Стартовый скрипт для тестирования VFS с несколькими файлами
# Файловая система: vfs_samples/several_files.json

# Вывод содержимого корня
ls

# Просмотр поддиректории
ls docs

# Переход в поддиректорию
cd docs
ls

# Возврат на уровень выше
cd ..
ls

# Сохранение VFS на диск
vfs-save saved_several.json

# Обработка ошибок: попытка cd в обычный файл
cd readme.txt

# Обработка ошибок: просмотр несуществующего пути
ls nowhere

exit
